// Helper to find carrier
const getCarrier = (id: string) => {
  const carrier = CARRIERS.find(c => c.id === id);
  if (!carrier) throw new Error(`Carrier ${id} not found`);
  return {
    id: carrier.id,
    name: carrier.name,
    dotNumber: carrier.dotNumber,
    mcNumber: carrier.mcNumber,
    verified: carrier.verified,
    rating: carrier.rating,
    reviewsCount: carrier.reviewsCount,
    yearsActive: carrier.yearsActive,
    phone: carrier.phone,
    email: carrier.email,
    location: carrier.location,
    logoInitials: carrier.logoInitials,
    gradient: carrier.gradient
  };
};

